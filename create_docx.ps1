<h3>4.4 การสร้างเครื่องมือประเมินประสิทธิภาพระบบ</h3>
<p>เครื่องมือที่ใช้ในการประเมินประสิทธิภาพและความพึงพอใจของผู้ใช้งาน ซึ่งคณะผู้จัดทำได้ดำเนินการสร้างและพัฒนาตามระเบียบวิธีวิจัย โดยมีรายละเอียดดังนี้</p>
<p><strong>4.4.1 วิธีและขั้นตอนการสร้างแบบประเมิน</strong><br>
การสร้างแบบประเมินประสิทธิภาพระบบมีขั้นตอนการดำเนินงาน ดังนี้<br>
1. ศึกษาและรวบรวมข้อมูลเกี่ยวกับฟังก์ชันการทำงานของระบบจัดการสินค้าคงคลัง<br>
2. ร่างข้อคำถามในแบบประเมินให้ครอบคลุมตามขอบเขตและวัตถุประสงค์ของโครงการ<br>
3. ปรึกษาผู้เชี่ยวชาญเพื่อตรวจสอบความถูกต้อง ความเหมาะสมของภาษา และปรับปรุงแก้ไขแบบสอบถามให้สมบูรณ์</p>

